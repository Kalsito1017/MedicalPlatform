#!/usr/bin/env bash
# Generate k8s/secret.yaml with real random values for the local Kubernetes
# stack. The file is gitignored (k8s/.gitignore) and must NEVER be committed.
#
#   scripts/k8s/gen-secret.sh              # writes k8s/secret.yaml
#   FORCE=1 scripts/k8s/gen-secret.sh      # overwrite an existing file
#
# Generated values are random; the demo login passwords are printed ONCE to
# the terminal at the end so they can be used to log in after seeding. The
# file itself holds every value (local only, mode 600).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
OUT="${SECRET_OUT:-${REPO_ROOT}/k8s/secret.yaml}"

if ! command -v openssl >/dev/null 2>&1; then
    echo "error: openssl not found; install it or edit k8s/secret.example.yaml by hand." >&2
    exit 1
fi

if [ -e "${OUT}" ] && [ "${FORCE:-0}" != "1" ]; then
    echo "error: ${OUT} already exists. Re-run with FORCE=1 to overwrite." >&2
    exit 1
fi

APP_SECRET_KEY="$(openssl rand -base64 48)"
DB_PASSWORD="$(openssl rand -hex 24)"
DEMO_ADMIN_PASSWORD="$(openssl rand -base64 12)"
DEMO_DOCTOR_PASSWORD="$(openssl rand -base64 12)"
DEMO_NURSE_PASSWORD="$(openssl rand -base64 12)"

# LLM key is optional: export LLM_API_KEY=... before running to include it.
LLM_LINE="# LLM_API_KEY: (omitted — export LLM_API_KEY before running gen-secret.sh to include it)"
if [ -n "${LLM_API_KEY:-}" ]; then
    LLM_LINE="LLM_API_KEY: \"${LLM_API_KEY}\""
fi

umask 077
cat >"${OUT}" <<EOF
# GENERATED by scripts/k8s/gen-secret.sh — LOCAL ONLY, NEVER COMMIT.
# Template with documented placeholders: k8s/secret.example.yaml
apiVersion: v1
kind: Secret
metadata:
  name: app-secret
  namespace: clinical
  labels:
    app.kubernetes.io/part-of: clinical-ai-platform
type: Opaque
stringData:
  APP_SECRET_KEY: "${APP_SECRET_KEY}"
  DATABASE_URL: "postgresql+asyncpg://app:${DB_PASSWORD}@db.clinical.svc:5432/clinical_demo" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  MIGRATION_DATABASE_URL: "postgresql+asyncpg://app:${DB_PASSWORD}@db.clinical.svc:5432/clinical_demo" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  POSTGRES_USER: "app"
  POSTGRES_PASSWORD: "${DB_PASSWORD}" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  POSTGRES_DB: "clinical_demo"
  DEMO_ADMIN_EMAIL: "admin@example.com"
  DEMO_ADMIN_PASSWORD: "${DEMO_ADMIN_PASSWORD}" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  DEMO_DOCTOR_EMAIL: "doctor@example.com"
  DEMO_DOCTOR_PASSWORD: "${DEMO_DOCTOR_PASSWORD}" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  DEMO_NURSE_EMAIL: "nurse@example.com"
  DEMO_NURSE_PASSWORD: "${DEMO_NURSE_PASSWORD}" # security-check-allow: locally generated by scripts/k8s/gen-secret.sh, gitignored
  ${LLM_LINE}
EOF
chmod 600 "${OUT}"

echo "wrote ${OUT} (mode 600, gitignored via k8s/.gitignore)"
echo
echo "Demo logins (also stored in the file above; shown here for convenience):"
echo "  admin  : admin@example.com / ${DEMO_ADMIN_PASSWORD}"
echo "  doctor : doctor@example.com / ${DEMO_DOCTOR_PASSWORD}"
echo "  nurse  : nurse@example.com / ${DEMO_NURSE_PASSWORD}"
